"""Sanity checks for the Phase 1 configuration foundation."""

import pytest

from src.utils.config import PROJECT_ROOT, load_config, resolve_path


def test_default_config_loads():
    config = load_config()
    for section in ("project", "paths", "data", "preprocessing", "model", "training", "evaluation", "inference"):
        assert section in config, f"missing config section: {section}"


def test_split_ratios_sum_to_one():
    split = load_config()["data"]["split"]
    assert split["train"] + split["val"] + split["test"] == pytest.approx(1.0)


def test_efficientnet_input_settings():
    config = load_config()
    assert config["model"]["backbone"] == "EfficientNetB0"
    assert config["preprocessing"]["image_size"] == [224, 224]
    assert config["preprocessing"]["channels"] == 3


def test_disclaimer_present():
    disclaimer = load_config()["inference"]["disclaimer"]
    assert "not a medical diagnosis" in disclaimer.lower()


def test_static_paths_exist():
    # train/validation/test/processed are generated by scripts/prepare_dataset.py
    paths = load_config()["paths"]
    for key in ("raw_data", "models", "reports"):
        assert resolve_path(paths[key]).is_dir(), f"paths.{key} -> {paths[key]} does not exist"


def test_dataset_section_is_complete():
    dataset = load_config()["dataset"]
    for key in ("name", "source_url", "download_url", "archive_name", "extract_dir", "source_subdir", "license"):
        assert dataset.get(key), f"dataset.{key} missing"
    assert load_config()["data"]["split"]["group_by"] == "patient_id"


def test_resolve_path_is_project_relative():
    assert resolve_path("models") == PROJECT_ROOT / "models"


def test_missing_config_raises(tmp_path):
    with pytest.raises(FileNotFoundError):
        load_config(tmp_path / "nope.yaml")
